import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import test from 'node:test';
const read=path=>readFile(new URL(`../${path}`,import.meta.url),'utf8');
test('Colzo is a genuinely new dashboard layout, not a palette-only skin',async()=>{
  const html=await read('index.html');
  assert.match(html,/class="colzo-command-hero"/);
  assert.match(html,/class="colzo-hero-content"/);
  assert.match(html,/class="colzo-hero-art"/);
  assert.match(html,/class="colzo-dashboard-section-title"/);
  assert.match(html,/COLZO <b>COMMAND CENTRE<\/b>/);
  assert.match(html,/class="colzo-hero-primary"/);
  assert.match(html,/onclick="showView\('leads'\)"/);
  assert.match(html,/onclick="showView\('enquiries'\)"/);
  assert.match(html,/id="stats"/);
  assert.match(html,/id="dashboardAiStatus"/);
  for (const section of ['leads','actions','bookings','settings']) assert.match(html,new RegExp(`data-view="${section}"`));
  assert.match(html,/class="auth-pending app-loading colzo-interface"/);
  assert.match(html,/<h1><span>Colzo<\/span><\/h1>/);
});
test('Colzo design layer loads AFTER legacy dynamically inserted themes',async()=>{
  const html=await read('index.html');
  const premium=html.indexOf('/assets/premium-ui.js');
  const mock=html.indexOf('/assets/mock-v3.js');
  const newUi=html.indexOf('/assets/colzo-interface.js');
  assert.ok(premium>0 && mock>premium && newUi>mock);
  const loader=await read('assets/colzo-interface.js');
  assert.match(loader,/document\.head\.appendChild\(link\)/);
  assert.match(loader,/colzo-interface\.css/);
  assert.match(loader,/document\.documentElement\.dataset\.productUi/);
  const css=await read('assets/colzo-interface.css');
  assert.match(css,/body\.colzo-interface\.auth-ready #dashboardView \.colzo-command-hero/);
  assert.match(css,/@media\(min-width:1040px\)/);
  assert.match(css,/body\.colzo-interface\.auth-ready \.bottom-nav/);
  assert.match(css,/@media\(max-width:560px\)/);
  assert.match(css,/#c8ff2e/i);
  assert.match(css,/#15181d/i);
});
test('Pilot-only dashboard is hidden without deleting business functionality',async()=>{
  const html=await read('index.html');
  const css=await read('assets/colzo-interface.css');
  assert.match(html,/id="pilotProgressCard"/);
  assert.match(css,/#dashboardView #pilotProgressCard\{display:none!important\}/);
  assert.match(html,/id="valueDashboardCard"/);
  assert.match(html,/id="activity"/);
  assert.match(html,/id="installAppCard"/);
});
