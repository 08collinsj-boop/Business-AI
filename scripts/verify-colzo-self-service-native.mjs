const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !k.startsWith('PG')));
const run = (name, args) => execFileSync(root ? 'python3' : join(bin, name), root
  ? ['-c', 'import os,sys; os.setgroups([]); os.setgid(65534); os.setuid(65534); os.execv(sys.argv[1],sys.argv[1:])', join(bin, name), ...args]
  : args, { env, stdio: 'pipe' });
const connection = { host: work, port: 55460, user: 'postgres', database: 'postgres', connectionTimeoutMillis: 5000 };
const connect = async (user = 'postgres') => { const c = new pg.Client({ ...connection, user }); await c.connect(); return c; };

const checks=[];
const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
const user=n=>'20000000-0000-4000-8000-'+String(n).padStart(12,'0');
const create=(client,n,ack=true)=>client.query('SELECT * FROM public.create_colzo_self_serve_pilot_workspace($1,$2,$3,$4,$5)',[user(n),'Fictional Workspace '+n,'Testing','fictional-workspace-'+n,ack]);
